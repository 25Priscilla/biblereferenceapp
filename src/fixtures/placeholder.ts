/**
 * ⚠ PLACEHOLDER FIXTURE — NOT SCRIPTURE ⚠
 *
 * Generates obviously-labelled stand-in text so the reader layout can be
 * designed and tested before any verified, licensed translation is
 * integrated (Phase 3). Nothing here is, or imitates, real Bible text.
 * Remove the fixture from user-facing builds once real data is available.
 */

import type { Chapter, TranslationInfo } from "../bible/types";

export const PLACEHOLDER_TRANSLATION: TranslationInfo = {
  id: "placeholder",
  abbreviation: "DEMO",
  name: "Placeholder text (no translation installed)",
  language: "en",
  source: "Generated by VersePath for layout testing",
  licence: "Not applicable — contains no Bible text",
  offlineAllowed: true,
  isPlaceholder: true,
};

const PLACEHOLDER_VERSE_COUNT = 12;

export function placeholderChapter(book: string, chapter: number): Chapter {
  return {
    translationId: PLACEHOLDER_TRANSLATION.id,
    book,
    chapter,
    verses: Array.from({ length: PLACEHOLDER_VERSE_COUNT }, (_, i) => ({
      number: i + 1,
      text:
        `[Placeholder for verse ${i + 1}.] Verified Scripture text will appear here ` +
        `once a licensed English or Malayalam translation has been integrated.`,
    })),
  };
}
